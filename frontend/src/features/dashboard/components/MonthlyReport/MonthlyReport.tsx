import { FileDown,Sparkles,Loader2 } from "lucide-react";
import {styles} from './MonthlyReport.styles';

type MonthlyReportProps={
    selectedMonth:number;
    selectedYear:number;
    onMonthChange:(month:number)=> void;
    onYearChange:(year:number)=> void;
    onDownload:()=> void;
    downloading:boolean;
};

const MONTHS= [
  { value: 1,  label: "January"   },
  { value: 2,  label: "February"  },
  { value: 3,  label: "March"     },
  { value: 4,  label: "April"     },
  { value: 5,  label: "May"       },
  { value: 6,  label: "June"      },
  { value: 7,  label: "July"      },
  { value: 8,  label: "August"    },
  { value: 9,  label: "September" },
  { value: 10, label: "October"   },
  { value: 11, label: "November"  },
  { value: 12, label: "December"  },
];

// Generate last 5 years
const YEARS = Array.from({length:5},(_,i)=>{
    const year = new Date().getFullYear() - i;
    return {value:year,label:String(year)};
});

export function MonthlyReport({
    selectedMonth,
    selectedYear,
    onMonthChange,
    onYearChange,
    onDownload,
    downloading,
}:MonthlyReportProps){
    const monthLabel= MONTHS.find(m=> m.value === selectedMonth)?.label ?? "Month";
    return(
        <div className={styles.card()}>
            {/* Header */}
            <div className={styles.header()}>
                <h4 className={styles.titleText()}>Monthly Report</h4>
                <span className={styles.aiBadge()}>
                    <Sparkles size={12}/>
                    AI Powered
                </span>
            </div>

            {/* Month Selector */}
            <div className={styles.selectorRow()}>
                <span className={styles.selectorLabel()}>Month:</span>
                <select value={selectedMonth} onChange={(e)=> onMonthChange(Number(e.target.value))} className={styles.select()}>
                    {MONTHS.map((m)=> (
                        <option key={m.value} value={m.value}>{m.label}</option>
                    ))}
                </select>

                <select value={selectedYear} onChange={(e)=> onYearChange(Number(e.target.value))} className={styles.select()}>
                    {YEARS.map((y)=> (
                        <option key={y.value} value={y.value}>{y.label}</option>
                    ))}
                </select>
            </div>

            {/* Download button */}
            {downloading ? (
               <div className={styles.loadingBtn()}>
                 <Loader2 size={16} className="animate-spin" />
                 Generating PDF...
               </div>
             ) : (
               <button
                 onClick={onDownload}
                 className={styles.downloadBtn()}
               >
                 <FileDown size={16} className={styles.downloadIcon()} />
                 Download {monthLabel} {selectedYear} Report
               </button>
             )}

             <div className={styles.infoSection()}>
        <div className={styles.infoItem()}>
          <span className={styles.infoLabel()}>Report includes</span>
          <span className={styles.infoValue()}>AI Insights</span>
        </div>
        <div className={styles.infoItem()}>
          <span className={styles.infoLabel()}>Format</span>
          <span className={styles.infoValue()}>PDF</span>
        </div>
        <div className={styles.infoItem()}>
          <span className={styles.infoLabel()}>Data coverage</span>
          <span className={styles.infoValue()}>{monthLabel} {selectedYear}</span>
        </div>
        <div className={styles.infoItem()}>
          <span className={styles.infoLabel()}>Generated by</span>
          <span className={styles.infoValue()}>Gemini 2.5 Flash</span>
        </div>
      </div>
        
        </div>
    )
}

